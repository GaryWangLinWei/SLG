/**
 * 解析倒计时文本为剩余秒数。
 * 游戏倒计时只有两种格式:
 *   "1天01:49:12" → 1*86400 + 01:49:12
 *   "00:59:26"     → 59分26秒（HH:MM:SS，小时恒两位、可能为 00）
 *
 * OCR 容错:
 *   - "1夭" → "1天"
 *   - 冒号可能被识别为 "." 或 "："
 *   - "1天01:30:14" 中的"1天"可能被误识成"2:"等，导致前缀数字
 *     与时间粘连（如 "2:101:30:14"）。此时取末尾完整的 HH:MM:SS，
 *     其前面残留的数字按上述粘连规则处理。
 *   - 倒计时上方"剩余"标签可能被误识成数字，与时间粘连成四段
 *     （如 "68:02:10:32"）。真正的时间恒为末尾的 HH:MM:SS，锚定末尾
 *     提取即可，前面的 "68:" 作为噪声丢弃。
 *   - 尾部杂讯过滤
 *
 * 不接受 M:SS（游戏不存在该格式），因此"已完成""空闲"等中文被误识成
 * "54:4" 之类时返回 null（空闲/非倒计时）。
 *
 * 返回 null 表示无法解析（空闲、非倒计时文本等）。
 */
export function parseCountdown(text: string): number | null {
  // Normalize common OCR errors
  let t = text
    .replace(/夭/g, '天')
    .replace(/：/g, ':')
    .replace(/O/g, '0')
    .replace(/o/g, '0');

  // 先把点号转成冒号，但不要动小数点之类（倒计时里没有小数）；
  // 仅把独立的 "." 视作冒号
  t = t.replace(/\./g, ':');

  let days = 0;
  const dayMatch = t.match(/(\d+)\s*天/);
  if (dayMatch) {
    days = parseInt(dayMatch[1], 10);
  }

  // 提取末尾的 H:MM:SS（带秒）。分、秒位必须恰好两位（游戏倒计时恒补零）。
  // 锚定字符串末尾取最后一个完整时间，避免前缀杂讯污染。例如游戏里"剩余"两字
  // 可能被 OCR 误识成 "68"，与倒计时粘连成 "68:02:10:32"——真正的时间是末尾的
  // "02:10:32"。若用全局 matchAll 取最后匹配，"68:02:10" 会抢先匹配并消费掉
  // 字符，导致 "02:10:32" 无法匹配而误判为空闲，因此必须锚定末尾。
  const hmsMatch = t.match(/(\d{1,3}):(\d{2}):(\d{2})(?!\d)([^\d]*)$/);
  if (hmsMatch) {
    let h = parseInt(hmsMatch[1], 10);
    const mm = parseInt(hmsMatch[2], 10);
    const ss = parseInt(hmsMatch[3], 10);
    // 小时字段 >23 通常是"1天01"被粘连成"101"（"天"被识别成冒号/丢失），
    // 此时前导位是天数，末两位是小时。例如：
    //   "1天01:30:14" → "2:101:30:14" / ":101:14:45"
    // 游戏中超过 1 天的倒计时一律显示为 "X天HH:MM:SS"，不会出现 100+ 小时，
    // 因此把 3 位小时的百位还原成天是安全的。
    if (h > 23 && h >= 100 && h < 1000) {
      days += Math.floor(h / 100);
      h = h % 100;
    }
    // 合法性：时 <24、分秒 < 60
    if (h > 23 || mm >= 60 || ss >= 60) return null;
    return days * 86400 + h * 3600 + mm * 60 + ss;
  }

  // 游戏倒计时只有两种格式：
  //   带天：N天HH:MM:SS（如 "1天01:49:12"）
  //   不带天：HH:MM:SS（如 "00:59:26"，小时恒为两位、可能为 00）
  // 不存在 M:SS 形式。中文状态（"已完成""空闲"等）被 OCR 误识成 M:SS 形态
  // （如 "54:4"）时不应解析为倒计时，因此不再有 M:SS 兜底分支。

  // 只有天数也返回（如"1天"）
  if (days > 0) {
    return days * 86400;
  }

  // 注意：不接受纯数字。队列倒计时永远是 H:MM:SS / M:SS / X天… 格式，
  // 而"空闲中"等中文状态被 OCR 误识成单个数字（如"40"）时，
  // 若当作裸秒数返回会把空闲队列误判成还有倒计时。

  // 没有冒号时间格式 → 视为空闲
  return null;
}
